CATALOGS = {"ru": RU, "en": EN}


def normalize_language(value):
    return value if value in SUPPORTED_LANGUAGES else "ru"


def catalog(language):
    return CATALOGS[normalize_language(language)]


def translate(language, key, **values):
    result = catalog(language).get(key, RU.get(key, key))
    if isinstance(result, str) and values:
        return result.format(**values)
    return result
